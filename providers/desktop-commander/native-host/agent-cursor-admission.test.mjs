import assert from 'node:assert/strict';
import {admitCursorEvent} from './agent-cursor-admission.mjs';
const hash='a'.repeat(64);
const evt={agentId:'agent-lee',authority:'4citeB4U/LEEWAY-DEVICE-BRIDGE',requestId:'request-test-1234',actionId:'action-test-1234',device:'pc',ownerApproved:true,cancelled:false,action:'click',x:300,y:250,timestamp:Date.now()};
const exe={requestId:evt.requestId,actionId:evt.actionId,device:'pc',state:'EXECUTED',provider:'LEEWAY_DEVICE_BRIDGE',receiptHash:hash};
const obs={requestId:evt.requestId,actionId:evt.actionId,postStateVerified:true,receiptHash:hash};
let passed=0;
const t=(name,e,x=exe,o=obs,expected='HIDDEN')=>{const got=admitCursorEvent(e,x,o);assert.equal(got.state,expected,name);passed++;};
t('fully correlated',evt,exe,obs,'SHOW');
t('missing observation',evt,exe,null);
t('missing approval',{...evt,ownerApproved:false});
t('cancelled',{...evt,cancelled:true});
t('stale',{...evt,timestamp:Date.now()-6000});
t('wrong authority',{...evt,authority:'IMPOSTOR'});
t('wrong request',evt,{...exe,requestId:'other-request-1234'});
t('wrong action',evt,{...exe,actionId:'other-action-1234'});
t('unverified post state',evt,exe,{...obs,postStateVerified:false});
t('wrong receipt',evt,exe,{...obs,receiptHash:'b'.repeat(64)});
t('not executed',evt,{...exe,state:'PLANNED'});
t('bad coordinate',{...evt,x:-1});
t('arbitrary action',{...evt,action:'powershell'});
t('android matching',{...evt,device:'android',action:'tap'},{...exe,device:'android'},obs,'SHOW');
console.log('AGENT_CURSOR_ADMISSION_PASS '+passed+'/14; NO CURSOR ACTUATOR CLAIMED');
