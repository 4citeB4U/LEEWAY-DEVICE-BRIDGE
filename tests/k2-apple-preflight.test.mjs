import assert from 'node:assert/strict';
import {qualifyAppleEvidence} from '../operator/k2-apple-preflight.mjs';
const at=1792360000000;
const params={targetToken:'redacted-target-token',bundleId:'industries.leeway.devicebridge',version:'0.1.27',build:27,packageSha256:'833d88a1fb13248b326e39ac26b7c8fd02535202056d2824a47d413575eab007',at};
const sources={targetIdentity:'DEVICE_ENUMERATION',deviceTrust:'DEVICE_ENUMERATION',providerSession:'PROVIDER_SUPPORTED_STATUS',accountAuthorization:'PROVIDER_SUPPORTED_STATUS',signingIdentity:'SIGNING_METADATA',certificateValidity:'SIGNING_METADATA',profileBundle:'PROFILE_METADATA',profileDevice:'PROFILE_METADATA',entitlements:'PROFILE_METADATA'};
const make=()=>({observations:Object.entries(sources).map(([field,sourceType])=>({...params,field,sourceType,state:'PASS',observedAt:at}))});
const check=(v)=>qualifyAppleEvidence(v,params);
assert.equal(check(null).state,'INPUT_INCOMPLETE');
assert.equal(check({}).state,'OBSERVATIONS_MISSING');
assert.equal(check({observations:[]}).blockers.length,9);
assert.equal(check(make()).state,'EVIDENCE_SHAPE_QUALIFIED_ONLY');
assert.equal(check(make()).ready,false);
assert.equal(check(make()).installationAuthorized,false);
let x=make(); x.observations[0].targetToken='other'; assert.equal(check(x).results.targetIdentity,'TARGET_OR_BUNDLE_MISMATCH');
x=make(); x.observations[4].observedAt=at-600000; assert.equal(check(x).results.signingIdentity,'INVALID_OR_STALE_EVIDENCE');
x=make(); x.observations.push({...x.observations[3]}); assert.equal(check(x).results.accountAuthorization,'CONFLICTING_OBSERVATIONS');
x=make(); x.observations[5].state='FAIL'; assert.equal(check(x).results.certificateValidity,'FAIL');
x=make(); x.observations[7].sourceType='SELF_REPORTED'; assert.equal(check(x).results.profileDevice,'INVALID_OR_STALE_EVIDENCE');
x=make(); x.observations[5].sourceType='PROVIDER_SUPPORTED_STATUS'; assert.equal(check(x).results.certificateValidity,'INVALID_OR_STALE_EVIDENCE');
x=make(); x.observations[6].packageSha256='f'.repeat(64); assert.equal(check(x).results.profileBundle,'RELEASE_MISMATCH');
x=make(); x.observations[8].build=26; assert.equal(check(x).results.entitlements,'RELEASE_MISMATCH');
x=make(); x.observations[3].observedAt=at+1; assert.equal(check(x).results.accountAuthorization,'INVALID_OR_STALE_EVIDENCE');
assert.equal(qualifyAppleEvidence(make(),{...params,build:0}).state,'INPUT_INCOMPLETE');
